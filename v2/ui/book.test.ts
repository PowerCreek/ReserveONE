const text = (el: Element, sel: string) => el.querySelector(sel)?.textContent ?? ''
const type = (el: Element, sel: string, v: string) => ((i = el.querySelector<HTMLInputElement>(sel)!) => ((i.value = v), i.dispatchEvent(new i.ownerDocument.defaultView!.Event('input', {bubbles: true}))))()
const named = (app: ReturnType<typeof rig>['app'], name: string) => Object.values(app.store.state.world.ents).find(e => e.party?.name === name)!
test('wizard: steps, live availability with nearby times, feats and flags recorded; edit from the list saves in place', async () => {
  const {el, app} = rig()
  load(app, 'lunch')
  await settle()
  type(el, '[data-form="book"] [name=name]', 'Lee')
  type(el, '[data-form="book"] [name=size]', '4')
  click(el, '[data-act="bk-next"]')
  await settle()
  assert.equal(uiOf(app).bk!.step, 2)
  assert.ok(!el.querySelector<HTMLElement>('[data-show="ui.bk.on.2"]')!.hidden)
  assert.match(text(el, '[data-avail]'), /Available at/)
  click(el, '[data-bkfeats] [data-id="quiet"]')
  click(el, '[data-bkflags] [data-id="vip"]')
  await settle()
  assert.equal(el.querySelector('[data-bkfeats] [data-id="quiet"]')!.getAttribute('aria-checked'), 'true')
  type(el, '[data-form="book"] [name=size]', '40')
  await settle()
  assert.match(text(el, '[data-avail]'), /Not available.*No table takes a party of 40/s)
  type(el, '[data-form="book"] [name=size]', '4')
  click(el, '[data-act="book"]')
  const lee = named(app, 'Lee')
  assert.deepEqual([lee.party!.size, lee.intake!.flags, lee.wants!.list.map(w => w.feat)], [4, ['vip'], ['quiet']])
  assert.equal(uiOf(app).bk!.step, 1) // reset for the next booking
  await settle()
  click(el, `[data-res="${lee.id}"] [data-to="edit"]`)
  await settle()
  assert.equal(el.querySelector<HTMLInputElement>('[data-form="book"] [name=name]')!.value, 'Lee')
  assert.match(text(el, '[data-act="book"]'), /^Save/)
  type(el, '[data-form="book"] [name=size]', '5')
  click(el, '[data-act="book"]')
  assert.equal(named(app, 'Lee').party!.size, 5)
  assert.equal(having(app.store.state.world, 'party', 'reservation').length, 2)
})
