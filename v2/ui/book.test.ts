// Front-of-house UI (U14): booking wizard with live availability, the reservations list (slots, filters, details, actions), wait list, call-aheads and the priority queue.
import test from 'node:test'
import assert from 'node:assert/strict'
import {having} from '../contracts/index.ts'
import {settle} from '../test/dom.ts'
import {load} from './index.ts'
import {click, rig} from './rig.ts'
import {step} from './sim.ts'
import {uiOf} from './state.ts'
const text = (el: Element, sel: string) => el.querySelector(sel)?.textContent ?? ''
const type = (el: Element, sel: string, v: string) => ((i = el.querySelector<HTMLInputElement>(sel)!) => ((i.value = v), i.dispatchEvent(new i.ownerDocument.defaultView!.Event('input', {bubbles: true}))))()
const named = (app: ReturnType<typeof rig>['app'], name: string) => Object.values(app.store.state.world.ents).find(e => e.party?.name === name)!
test('wizard: steps, live availability with nearby times, feats and flags recorded; edit from the list saves in place', async () => {
  const {el, app} = rig()
  load(app, 'lunch')
  await settle()
  type(el, '[data-form="book"] [name=name]', 'Lee')
  type(el, '[data-form="book"] [name=size]', '4')
  click(el, '[data-act="bk-next"]')
  await settle()
  assert.equal(uiOf(app).bk!.step, 2)
  assert.ok(!el.querySelector<HTMLElement>('[data-show="ui.bk.on.2"]')!.hidden)
  assert.match(text(el, '[data-avail]'), /Available at/)
  click(el, '[data-bkfeats] [data-id="quiet"]')
  click(el, '[data-bkflags] [data-id="vip"]')
  await settle()
  assert.equal(el.querySelector('[data-bkfeats] [data-id="quiet"]')!.getAttribute('aria-checked'), 'true')
  type(el, '[data-form="book"] [name=size]', '40')
  await settle()
  assert.match(text(el, '[data-avail]'), /Not available.*No table takes a party of 40/s)
  type(el, '[data-form="book"] [name=size]', '4')
  click(el, '[data-act="book"]')
  const lee = named(app, 'Lee')
  assert.deepEqual([lee.party!.size, lee.intake!.flags, lee.wants!.list.map(w => w.feat)], [4, ['vip'], ['quiet']])
  assert.equal(uiOf(app).bk!.step, 1) // reset for the next booking
  await settle()
  click(el, `[data-res="${lee.id}"] [data-to="edit"]`)
  await settle()
  assert.equal(el.querySelector<HTMLInputElement>('[data-form="book"] [name=name]')!.value, 'Lee')
  assert.match(text(el, '[data-act="book"]'), /^Save/)
  type(el, '[data-form="book"] [name=size]', '5')
  click(el, '[data-act="book"]')
  assert.equal(named(app, 'Lee').party!.size, 5)
  assert.equal(having(app.store.state.world, 'party', 'reservation').length, 2)
})
test('list: slots with covers, filters by state and size, details open, cancel keeps the row under Cancelled', async () => {
  const {el, app} = rig()
  load(app, 'lunch')
  await settle()
  const alv = named(app, 'Alvarez')
  assert.ok(el.querySelector(`[data-book] [data-slot] [data-res="${alv.id}"]`))
  assert.match(text(el, '[data-book] [data-slot]'), /2 covers/)
  click(el, `[data-res="${alv.id}"] [data-act="bk-open"]`)
  await settle()
  assert.match(text(el, `[data-bkdetail="${alv.id}"]`), /Phone/)
  click(el, '[data-act="bk-filter"][data-kind="size"][data-id="5+"]')
  await settle()
  assert.equal(el.querySelectorAll('[data-book] [data-res]').length, 0)
  click(el, '[data-act="bk-filter"][data-kind="size"][data-id="any"]')
  await settle()
  click(el, `[data-res="${alv.id}"] [data-to="cancel"]`)
  await settle()
  assert.equal(el.querySelectorAll(`[data-book] [data-res="${alv.id}"]`).length, 0) // open filter hides it
  click(el, '[data-act="bk-filter"][data-kind="state"][data-id="CANCELLED"]')
  await settle()
  assert.match(text(el, `[data-book] [data-res="${alv.id}"]`), /cancelled/)
})
test('wait list + call-ahead + priority queue: quote, add with flags, ETA joins the queue, check in, bump with a reason, text, remove', async () => {
  const {el, app} = rig()
  load(app, 'lunch')
  uiOf(app).rate = 0
  await settle()
  assert.match(text(el, '[data-wlq]'), /Quote for 2/)
  type(el, '[name=wl-name]', 'Ng')
  click(el, '[data-wlflags] [data-id="access"]')
  click(el, '[data-act="wl-add"]')
  const ng = named(app, 'Ng')
  assert.deepEqual([ng.intake!.via, ng.intake!.flags, ng.queue!.status], ['walk', ['access'], 'WAITING'])
  assert.equal(el.querySelector<HTMLInputElement>('[name=wl-name]')!.value, '')
  type(el, '[name=ca-name]', 'Kim')
  type(el, '[name=ca-eta]', '5')
  click(el, '[data-act="ca-add"]')
  await settle()
  const kim = named(app, 'Kim')
  assert.match(text(el, `[data-calls] [data-call="${kim.id}"]`), /ETA .* \(in 5m\)/)
  assert.equal(el.querySelectorAll(`[data-queue] [data-party="${kim.id}"]`).length, 0)
  step(app, 6 * 60000)
  await settle()
  assert.match(text(el, `[data-queue] [data-party="${kim.id}"]`), /not here yet.*Call-ahead \+200/s)
  click(el, `[data-queue] [data-party="${kim.id}"] [data-to="arrive"]`)
  assert.equal(named(app, 'Kim').queue!.status, 'WAITING')
  await settle()
  const order = () => [...el.querySelectorAll('[data-queue] > li')].map(li => li.getAttribute('data-party'))
  const last = order().at(-1)!
  const sel = el.querySelector<HTMLSelectElement>('[data-qwhy] select')!
  sel.value = 'apology'
  sel.dispatchEvent(new sel.ownerDocument.defaultView!.Event('change', {bubbles: true}))
  click(el, `[data-queue] [data-party="${last}"] [data-to="up"]`)
  await settle()
  assert.equal(order().at(-2), last)
  assert.match(text(el, `[data-queue] [data-party="${last}"] [data-why]`), /bumped: Make up for a long wait/)
  click(el, `[data-queue] [data-party="${last}"] [data-to="text"]`)
  await settle()
  assert.match(text(el, `[data-queue] [data-party="${last}"]`), /texted: table ready/)
  click(el, `[data-queue] [data-party="${last}"] [data-to="removed"]`)
  await settle()
  assert.ok(!order().includes(last))
  assert.equal(app.store.state.world.ents[last].intake!.gone!.why, 'removed')
})
